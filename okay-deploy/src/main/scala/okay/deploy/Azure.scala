  private def setup(d: Deployment, services: Vector[Service]): String =
    val sb = new StringBuilder
    sb ++= s"""#!/bin/sh
              |# generated by okay-deploy from ${d.name}'s Deployment value
              |#
              |# The Key Vault and every secret in it, created BEFORE terraform
              |# runs. Terraform READS these; it never holds one, because
              |# `apply` writes every attribute into the state file.
              |#
              |# No value is in this file and none ever will be.
              |set -e
              |GROUP=$${AZURE_RESOURCE_GROUP:-${d.name}}
              |VAULT=$${AZURE_VAULT:?set AZURE_VAULT to the Key Vault name — it is globally unique}
              |LOCATION=$${AZURE_LOCATION:-${services.headOption.flatMap(_.region).getOrElse("")}}
              |
              |az group create --name "$$GROUP" --location "$$LOCATION" >/dev/null
              |az keyvault create --name "$$VAULT" --resource-group "$$GROUP" --location "$$LOCATION" >/dev/null 2>&1 || true
              |
              |create() { # name, value
              |  az keyvault secret set --vault-name "$$VAULT" --name "$$1" --value "$$2" >/dev/null
              |  echo "  $$1"
              |}
              |
              |""".stripMargin
    var any = false
    for s <- services do
      val full = s"${d.name}-${s.name}"
      val names = Aws.secretsOf(s).map(n => n -> s"read by ${s.name} as $n") ++
        s.databases.map(db => Aws.passwordName(db) -> s"the password for the ${db.engine} beside ${s.name}")
      if names.nonEmpty then
        any = true
        sb ++= s"echo ${q(s"${s.name}:")}\n"
        for (n, why) <- names do
          sb ++= s"""create ${q(kvName(s"$full-$n"))} "$${$n:?set $n in your own environment — ${Shell.prompt(why)}}"\n"""
        sb ++= "\n"
    if !any then sb ++= "echo 'this deployment reads no secrets; the vault above is still where they would go.'\n"
    sb.result()

  private def imageOf(d: Deployment, s: Service): String = s.run match
    case Run.Image(repo, tag) => s"$repo:$tag"
    case _: Run.Module => s"${d.name}.azurecr.io/${s.name}:latest"

  private def databaseEnv(s: Service, r: String): Vector[(String, String)] =
    s.databases.map { db =>
      val dr = s"${r}_${ref(db.as)}"
      val host = s"$${azurerm_postgresql_flexible_server.$dr.fqdn}"
      val url = db.engine match
        case Engine.Postgres => s"jdbc:postgresql://$host:${db.engine.port}/${db.database}"
        case Engine.Mongo => s"mongodb://$host:${db.engine.port}/${db.database}"
        case _ => host
      Settings.envName("", s"${db.as}_url") -> url
    } ++ s.caches.map { c =>
      val cr = s"${r}_${ref(c.as)}"
      Settings.envName("", s"${c.as}_url") ->
        s"$${azurerm_redis_cache.$cr.hostname}:$${azurerm_redis_cache.$cr.ssl_port}"
    }

  /** a Key Vault secret name: letters, digits and dashes only */
  private[deploy] def kvName(s: String): String =
    s.map(c => if c.isLetterOrDigit then c else '-').replaceAll("-+", "-").stripPrefix("-").stripSuffix("-")

  /** a storage account name: lower-case letters and digits, no more */
  private def sanitize(s: String): String = s.filter(_.isLetterOrDigit).toLowerCase.take(16)

  private def cpu(s: Service): String =
    s.resources.map(_.cpuLimit).map { c =>
      if c.endsWith("m") then (c.dropRight(1).toDouble / 1000.0).toString else c.toDouble.toString
    }.getOrElse("0.25")

  private def memory(s: Service): String =
    s.resources.map(_.memoryLimit).map { m =>
      if m.toLowerCase.endsWith("gi") then s"${m.dropRight(2)}Gi"
      else s"${math.max(1, m.toLowerCase.stripSuffix("mi").toInt / 1024)}Gi"
    }.getOrElse("0.5Gi")

  private def ref(s: String): String =
    val cleaned = s.map(c => if c.isLetterOrDigit then c else '_')
    if cleaned.headOption.exists(_.isDigit) then s"_$cleaned" else cleaned

  private def str(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
  private def q(s: String): String = "'" + s.replace("'", "'\\''") + "'"
