package okay.deploy

import java.nio.file.Path

/**
 * Google Cloud, as Terraform for Cloud Run (specs/deployment.md,
 * stage 3).
 *
 * The same shape as `aws` and the same gate. What is different is
 * where the platform is, and one place where it is NOT: a
 * `Need.Volume` is REFUSED here. Cloud Run can mount a GCS bucket
 * through gcsfuse, and that is object storage wearing a filesystem —
 * no atomic rename, no locking — which is exactly what okay-persist's
 * log is built on. A deployment that mounted one would work in a demo
 * and corrupt a log under concurrency.
 */
object Gcp extends Target:
  val name = "gcp"

  def requires(d: Deployment): Vector[String] = Vector("terraform", "gcloud")

  def up(dir: Path): Vector[String] = Vector("terraform", s"-chdir=${dir.toString}", "apply")
  def down(dir: Path): Vector[String] = Vector("terraform", s"-chdir=${dir.toString}", "destroy")

  def render(d: Deployment): Either[String, Vector[(String, String)]] =
    val noRegion = d.services.filter(_.region.isEmpty).map(_.name)
    val volumes = d.services.filter(_.volumes.nonEmpty).map(_.name)
    if noRegion.nonEmpty then
      Left(s"gcp needs a region for ${noRegion.mkString(", ")} and no target can invent one — " +
        "add Need.Region(\"europe-west1\") (or wherever your users are)")
    else if volumes.nonEmpty then
      Left(s"${volumes.mkString(", ")} needs a durable directory and Cloud Run has none — " +
        "the bucket it can mount is object storage through gcsfuse, with no atomic rename and no " +
        "locking, and okay-persist's log needs both. Use the `cluster` target on GKE, which has real " +
        "persistent disks, or point the service at a database instead of a directory")
    else d.ordered.map { services =>
      Vector(
        "main.tf" -> Aws.align(main(d, services)),
        "setup.sh" -> setup(d, services)) ++
        services.map(s => s"${s.name}.tf" -> Aws.align(serviceTf(d, s))) ++
        d.extra.filter(_.target == name).map(e => e.path -> e.content)
    }

