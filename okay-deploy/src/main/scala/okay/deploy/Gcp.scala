  private def setup(d: Deployment, services: Vector[Service]): String =
    val sb = new StringBuilder
    sb ++= s"""#!/bin/sh
              |# generated by okay-deploy from ${d.name}'s Deployment value
              |#
              |# Every secret this deployment reads, created BEFORE terraform runs.
              |#
              |# Why here and not in a .tf file: `terraform apply` writes every
              |# resource attribute into the state file, and a secret version
              |# would put the VALUE there in plaintext.
              |#
              |# No value is in this file and none ever will be.
              |set -e
              |PROJECT=$${GOOGLE_PROJECT:?set GOOGLE_PROJECT to the project this deploys into}
              |
              |create() { # name, value
              |  gcloud secrets create "$$1" --project "$$PROJECT" --replication-policy=automatic >/dev/null 2>&1 || true
              |  printf '%s' "$$2" | gcloud secrets versions add "$$1" --project "$$PROJECT" --data-file=- >/dev/null
              |  echo "  $$1"
              |}
              |
              |""".stripMargin
    var any = false
    for s <- services do
      val full = s"${d.name}-${s.name}"
      val names = Aws.secretsOf(s).map(n => n -> s"read by ${s.name} as $n") ++
        s.databases.map(db => Aws.passwordName(db) -> s"the password for the ${db.engine} beside ${s.name}")
      if names.nonEmpty then
        any = true
        sb ++= s"echo ${q(s"${s.name}:")}\n"
        for (n, why) <- names do
          sb ++= s"""create ${q(s"$full-$n")} "$${$n:?set $n in your own environment — ${Shell.prompt(why)}}"\n"""
        sb ++= "\n"
    if !any then sb ++= "echo 'this deployment reads no secrets; nothing to create.'\n"
    sb.result()

  private def imageOf(d: Deployment, s: Service): String = s.run match
    case Run.Image(repo, tag) => s"$repo:$tag"
    case _: Run.Module => s"gcr.io/PROJECT/${d.name}-${s.name}:latest"

  private def databaseEnv(s: Service, r: String): Vector[(String, String)] =
    s.databases.map { db =>
      val dr = s"${r}_${ref(db.as)}"
      val host = s"$${google_sql_database_instance.$dr.private_ip_address}"
      val url = db.engine match
        case Engine.Postgres => s"jdbc:postgresql://$host:${db.engine.port}/${db.database}"
        case Engine.Mongo => s"mongodb://$host:${db.engine.port}/${db.database}"
        case _ => host
      Settings.envName("", s"${db.as}_url") -> url
    } ++ s.caches.map { c =>
      val cr = s"${r}_${ref(c.as)}"
      Settings.envName("", s"${c.as}_url") ->
        s"$${google_redis_instance.$cr.host}:$${google_redis_instance.$cr.port}"
    }

  private def sqlVersion(db: Need.Database): String = db.engine match
    case Engine.Postgres => "POSTGRES_" + db.version.takeWhile(_ != '.')
    case other => other.toString.toUpperCase

  private def ref(s: String): String =
    val cleaned = s.map(c => if c.isLetterOrDigit then c else '_')
    if cleaned.headOption.exists(_.isDigit) then s"_$cleaned" else cleaned

  private def str(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
  private def q(s: String): String = "'" + s.replace("'", "'\\''") + "'"
