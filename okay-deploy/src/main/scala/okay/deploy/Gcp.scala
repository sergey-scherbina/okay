  private def main(d: Deployment, services: Vector[Service]): String =
    val region = services.headOption.flatMap(_.region).getOrElse("")
    val sb = new StringBuilder
    sb ++= s"""# generated by okay-deploy from ${d.name}'s Deployment value — edit the value, not this file
              |#
              |# THE PROJECT IS NOT OURS. `project` has no default: a Google
              |# project is a billing boundary and an IAM boundary, and no
              |# deployment renderer should pick one for you.
              |
              |terraform {
              |  required_version = ">= 1.5"
              |  required_providers {
              |    google = {
              |      source  = "hashicorp/google"
              |      version = "~> 6.0"
              |    }
              |  }
              |}
              |
              |provider "google" {
              |  project = var.project
              |  region  = var.region
              |}
              |
              |variable "project" {
              |  description = "the Google project this runs in — a billing and IAM boundary, so it has no default"
              |  type        = string
              |}
              |
              |variable "region" {
              |  description = "where this runs"
              |  type        = string
              |  default     = ${str(region)}
              |}
              |
              |# the identity the services run AS — not the one that deploys
              |# them, which is yours
              |resource "google_service_account" "run" {
              |  account_id   = ${str(s"${d.name}-run".take(30))}
              |  display_name = ${str(s"${d.name} services")}
              |}
              |""".stripMargin
    if services.exists(_.databases.nonEmpty) then
      sb ++= s"""
                |# a private address for the databases below, so nothing is
                |# reachable from the internet that does not have to be
                |resource "google_compute_global_address" "private" {
                |  name          = ${str(s"${d.name}-private")}
                |  purpose       = "VPC_PEERING"
                |  address_type  = "INTERNAL"
                |  prefix_length = 16
                |  network       = "default"
                |}
                |
                |resource "google_service_networking_connection" "private" {
                |  network                 = "projects/$${var.project}/global/networks/default"
                |  service                 = "servicenetworking.googleapis.com"
                |  reserved_peering_ranges = [google_compute_global_address.private.name]
                |}
                |""".stripMargin
    sb.result()

  private def serviceTf(d: Deployment, s: Service): String =
    val r = ref(s.name)
    val full = s"${d.name}-${s.name}"
    val sb = new StringBuilder
    sb ++= "# generated by okay-deploy — edit the Deployment value, not this file\n\n"

    for name <- Aws.secretsOf(s) do
      sb ++= s"""# created OUT OF BAND by setup.sh: `terraform apply` writes every
                |# attribute into the state file, and a secret VERSION would put
                |# the value there in plaintext
                |data "google_secret_manager_secret" ${str(ref(name))} {
                |  secret_id = ${str(s"$full-$name")}
                |}
                |
                |resource "google_secret_manager_secret_iam_member" ${str(ref(name))} {
                |  secret_id = data.google_secret_manager_secret.${ref(name)}.id
                |  role      = "roles/secretmanager.secretAccessor"
                |  member    = "serviceAccount:$${google_service_account.run.email}"
                |}
                |
                |""".stripMargin

    for db <- s.databases do
      val dr = s"${r}_${ref(db.as)}"
      sb ++= s"""data "google_secret_manager_secret_version" ${str(s"${dr}_password")} {
                |  secret = ${str(s"$full-${Aws.passwordName(db)}")}
                |}
                |
                |resource "google_sql_database_instance" ${str(dr)} {
                |  name             = ${str(s"$full-${db.as}")}
                |  database_version = ${str(sqlVersion(db))}
                |  region           = var.region
                |
                |  # a managed database is the one thing here you cannot
                |  # re-create from this file: turn these on before you rely on it
                |  deletion_protection = false
                |
                |  settings {
                |    tier = "db-f1-micro"
                |
                |    backup_configuration {
                |      enabled = true
                |    }
                |
                |    ip_configuration {
                |      ipv4_enabled    = false
                |      private_network = "projects/$${var.project}/global/networks/default"
                |    }
                |  }
                |
                |  depends_on = [google_service_networking_connection.private]
                |}
                |
                |resource "google_sql_database" ${str(dr)} {
                |  name     = ${str(db.database)}
                |  instance = google_sql_database_instance.$dr.name
                |}
                |
                |resource "google_sql_user" ${str(dr)} {
                |  name     = ${str(db.as)}
                |  instance = google_sql_database_instance.$dr.name
                |  password = data.google_secret_manager_secret_version.${dr}_password.secret_data
                |}
                |
                |""".stripMargin

    for c <- s.caches do
      val cr = s"${r}_${ref(c.as)}"
      sb ++= s"""resource "google_redis_instance" ${str(cr)} {
                |  name           = ${str(s"$full-${c.as}")}
                |  tier           = "BASIC"
                |  memory_size_gb = 1
                |  region         = var.region
                |}
                |
                |""".stripMargin

    sb ++= s"""resource "google_cloud_run_v2_service" ${str(r)} {
              |  name     = ${str(full)}
              |  location = var.region
              |
              |  # Cloud Run is public by a flag, and its own name has a
              |  # managed certificate from the moment it exists
              |  ingress = ${if s.ports.exists(_.public) then "\"INGRESS_TRAFFIC_ALL\"" else "\"INGRESS_TRAFFIC_INTERNAL_ONLY\""}
              |
              |  template {
              |    service_account = google_service_account.run.email
              |
              |    scaling {
              |      min_instance_count = ${s.scale.replicas}
              |    }
              |
              |    containers {
              |      image = ${str(imageOf(d, s))}
              |""".stripMargin
    s.mainPort.foreach { port =>
      sb ++= s"""
                |      ports {
                |        container_port = $port
                |      }
                |""".stripMargin
    }
    for (k, v) <- s.settings.env ++ databaseEnv(s, r) do
      sb ++= s"""
                |      env {
                |        name  = ${str(k)}
                |        value = ${str(v)}
                |      }
                |""".stripMargin
    for n <- Aws.secretsOf(s) do
      sb ++= s"""
                |      env {
                |        name = ${str(n)}
                |
                |        value_source {
                |          secret_key_ref {
                |            secret  = data.google_secret_manager_secret.${ref(n)}.secret_id
                |            version = "latest"
                |          }
                |        }
                |      }
                |""".stripMargin
    s.resources.foreach { res =>
      sb ++= s"""
                |      resources {
                |        limits = {
                |          cpu    = ${str(res.cpuLimit)}
                |          memory = ${str(res.memoryLimit.replace("Mi", "Mi").replace("Gi", "Gi"))}
                |        }
                |      }
                |""".stripMargin
    }
    s.mainPort.foreach { port =>
      sb ++= s"""
                |      startup_probe {
                |        http_get {
                |          path = ${str(s.health.livenessPath)}
                |          port = $port
                |        }
                |
                |        period_seconds    = 5
                |        failure_threshold = ${math.max(1, s.health.startupSeconds / 5)}
                |      }
                |
                |      liveness_probe {
                |        http_get {
                |          path = ${str(s.health.livenessPath)}
                |          port = $port
                |        }
                |
                |        period_seconds = 10
                |      }
                |""".stripMargin
    }
    sb ++= """    }
             |  }
             |}
             |""".stripMargin

    if s.ports.exists(_.public) then
      sb ++= s"""
                |# public, because the value said the port was
                |resource "google_cloud_run_v2_service_iam_member" ${str(r)} {
                |  name     = google_cloud_run_v2_service.$r.name
                |  location = google_cloud_run_v2_service.$r.location
                |  role     = "roles/run.invoker"
                |  member   = "allUsers"
                |}
                |
                |output "${r}_url" {
                |  description = "the platform's own name, with a managed certificate from the moment it exists"
                |  value       = google_cloud_run_v2_service.$r.uri
                |}
                |""".stripMargin

    for (host, i) <- s.dns.zipWithIndex do
      sb ++= s"""
                |# A CUSTOM DOMAIN NEEDS VERIFICATION FIRST: a TXT record
                |# proving you own $host, checked by Google, before a
                |# certificate is issued. No Terraform resource does that for
                |# you — run `gcloud domains verify $host` and then apply.
                |resource "google_cloud_run_domain_mapping" ${str(s"${r}_domain_$i")} {
                |  name     = ${str(host)}
                |  location = var.region
                |
                |  metadata {
                |    namespace = var.project
                |  }
                |
                |  spec {
                |    route_name = google_cloud_run_v2_service.$r.name
                |  }
                |}
                |""".stripMargin
    sb.result()

